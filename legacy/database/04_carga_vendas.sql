DECLARE @R BIGINT, @K INT, @QT INT, @CPF9 VARCHAR(9), @CPF VARCHAR(11), @J INT, @S INT, @D1 INT, @D2 INT,
        @N1 INT, @S1 INT, @S2 INT, @C INT, @RUA INT, @PROF INT, @QN INT, @QS INT, @QC INT, @QR INT, @QP INT,
        @NOME VARCHAR(30), @SOB1 VARCHAR(30), @SOB2 VARCHAR(30)

SELECT @QN = COUNT(*) FROM @NOMES
SELECT @QS = COUNT(*) FROM @SOBRENOMES
SELECT @QC = COUNT(*) FROM @CIDADES
SELECT @QR = COUNT(*) FROM @RUAS
SELECT @QP = COUNT(*) FROM @PROFISSOES

SET @R = 20051121
SET @QT = 240
SET @K = 1

WHILE (SELECT COUNT(*) FROM TB_CONSORCIADO) < @QT
BEGIN
    -- CPF: 9 digitos pseudo-aleatorios + DV
    SET @R = (@R * 1103515245 + 12345) % 2147483648
    SET @CPF9 = RIGHT('000000000' + CAST((@R * 7919) % 1000000000 AS VARCHAR(10)), 9)

    SET @S = 0 SET @J = 1
    WHILE @J <= 9 BEGIN SET @S = @S + CAST(SUBSTRING(@CPF9, @J, 1) AS INT) * (11 - @J) SET @J = @J + 1 END
    SET @D1 = 11 - (@S % 11) IF @D1 >= 10 SET @D1 = 0
    SET @CPF = @CPF9 + CAST(@D1 AS CHAR(1))
    SET @S = 0 SET @J = 1
    WHILE @J <= 10 BEGIN SET @S = @S + CAST(SUBSTRING(@CPF, @J, 1) AS INT) * (12 - @J) SET @J = @J + 1 END
    SET @D2 = 11 - (@S % 11) IF @D2 >= 10 SET @D2 = 0
    SET @CPF = @CPF + CAST(@D2 AS CHAR(1))

    SET @R = (@R * 1103515245 + 12345) % 2147483648  SET @N1 = (@R / 65536) % @QN + 1
    SET @R = (@R * 1103515245 + 12345) % 2147483648  SET @S1 = (@R / 65536) % @QS + 1
    SET @R = (@R * 1103515245 + 12345) % 2147483648  SET @S2 = (@R / 65536) % @QS + 1
    SET @R = (@R * 1103515245 + 12345) % 2147483648  SET @C  = (@R / 65536) % @QC + 1
    SET @R = (@R * 1103515245 + 12345) % 2147483648  SET @RUA = (@R / 65536) % @QR + 1
    SET @R = (@R * 1103515245 + 12345) % 2147483648  SET @PROF = (@R / 65536) % @QP + 1

    IF @S2 = @S1 SET @S2 = @S1 % @QS + 1

    SELECT @NOME = NOME FROM @NOMES WHERE I = @N1
    SELECT @SOB1 = NOME FROM @SOBRENOMES WHERE I = @S1
    SELECT @SOB2 = NOME FROM @SOBRENOMES WHERE I = @S2

    IF dbo.FN_CPF_VALIDO(@CPF) = 1 AND NOT EXISTS (SELECT 1 FROM TB_CONSORCIADO WHERE NR_CPF = @CPF)
    BEGIN
        INSERT INTO TB_CONSORCIADO (NR_CPF, NM_CONSORCIADO, DT_NASCIMENTO, NR_RG, ID_ESTADO_CIVIL, DS_PROFISSAO, VL_RENDA_MENSAL,
                                    DS_EMAIL, NR_TELEFONE, NR_CELULAR, DS_LOGRADOURO, NR_ENDERECO, DS_COMPLEMENTO, NM_BAIRRO,
                                    NM_CIDADE, SG_UF, NR_CEP, DT_CADASTRO, CD_USUARIO_CADASTRO)
        SELECT @CPF,
               @NOME + ' ' + @SOB1 + ' ' + @SOB2,
               DATEADD(DAY, CAST(@R % 15000 AS INT), '19620101'),
               CAST(1000000000 + (@R % 899999999) AS VARCHAR(15)),
               (@R % 5) + 1,
               P.NOME,
               ROUND(2800 + (@R % 2300) * 10, -2),
               CASE WHEN @R % 9 = 0 THEN NULL
                    ELSE LOWER(@NOME) + '.' + LOWER(REPLACE(@SOB1, ' ', '')) + CAST(@R % 100 AS VARCHAR) + '@email.com.br' END,
               CASE WHEN @R % 4 = 0 THEN '(' + C.DDD + ') 3' + RIGHT('0000000' + CAST(@R % 10000000 AS VARCHAR), 7) ELSE NULL END,
               '(' + C.DDD + ') 9' + RIGHT('00000000' + CAST((@R * 31) % 100000000 AS VARCHAR), 8),
               U.NOME,
               CAST((@R % 2900) + 10 AS VARCHAR),
               CASE WHEN @R % 3 = 0 THEN 'AP ' + CAST((@R % 12) + 1 AS VARCHAR) + '0' + CAST((@R % 4) + 1 AS VARCHAR) ELSE NULL END,
               'CENTRO',
               C.CIDADE, C.UF,
               C.CEP + RIGHT('00000' + CAST(@R % 100000 AS VARCHAR), 5),
               '20260401', 2
          FROM @CIDADES C, @RUAS U, @PROFISSOES P
         WHERE C.I = @C AND U.I = @RUA AND P.I = @PROF
    END

    SET @K = @K + 1
END
