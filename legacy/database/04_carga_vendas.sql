/* Procedure auxiliar de venda (temporaria) -------------------------------- */
CREATE PROCEDURE #VENDE
    @CD_GRUPO       INT,
    @CD_CONSORCIADO INT,
    @CD_BEM         INT,
    @CD_VENDEDOR    INT,
    @DT_PROPOSTA    DATETIME,
    @ID_SIT_FINAL   TINYINT,           -- 1 digitada, 2 aguardando, 3 efetivada, 4 cancelada
    @CD_PROPOSTA    INT = NULL OUTPUT
AS
SET NOCOUNT ON
DECLARE @N SMALLINT, @TA DECIMAL(9,4), @ANT DECIMAL(9,4), @FR DECIMAL(9,4), @CD_PLANO INT,
        @VL_BEM MONEY, @PC1 DECIMAL(9,6), @VL1 MONEY, @CD_PV INT, @NR VARCHAR(12), @CD_COTA INT, @DT_PAG DATETIME

SELECT @N = QT_PRAZO_MESES - QT_ASSEMBLEIAS_REALIZADAS, @TA = PC_TAXA_ADM, @ANT = PC_ANTECIPACAO_TA,
       @FR = PC_FUNDO_RESERVA, @CD_PLANO = CD_PLANO
  FROM TB_GRUPO WHERE CD_GRUPO = @CD_GRUPO

SET @PC1 = ROUND(100.0 / @N, 6) + ROUND((@TA - @ANT) / @N, 6) + @ANT + ROUND(@FR / @N, 6)
SET @VL_BEM = dbo.FN_VALOR_BEM(@CD_BEM, @DT_PROPOSTA)
SET @VL1 = ROUND(@VL_BEM * @PC1 / 100, 2)

SELECT @CD_PV = CD_PONTO_VENDA FROM TB_VENDEDOR WHERE CD_VENDEDOR = @CD_VENDEDOR

SELECT @NR = CAST(YEAR(@DT_PROPOSTA) AS VARCHAR) + '-' + RIGHT('000000' + CAST(COUNT(*) + 1 AS VARCHAR), 6)
  FROM TB_PROPOSTA WHERE NR_PROPOSTA LIKE CAST(YEAR(@DT_PROPOSTA) AS VARCHAR) + '-%'

INSERT INTO TB_PROPOSTA (NR_PROPOSTA, CD_CONSORCIADO, CD_PLANO, CD_GRUPO, CD_BEM, CD_PONTO_VENDA, CD_VENDEDOR,
                         DT_PROPOSTA, DT_ASSINATURA, VL_BEM_PROPOSTA, VL_PRIMEIRA_PARCELA, ID_SITUACAO, DT_SITUACAO,
                         DT_CADASTRO, CD_USUARIO_CADASTRO)
VALUES (@NR, @CD_CONSORCIADO, @CD_PLANO, @CD_GRUPO, @CD_BEM, @CD_PV, @CD_VENDEDOR,
        @DT_PROPOSTA, CASE WHEN @ID_SIT_FINAL = 1 THEN NULL ELSE @DT_PROPOSTA END, @VL_BEM, @VL1,
        CASE WHEN @ID_SIT_FINAL = 3 THEN 2 ELSE @ID_SIT_FINAL END, @DT_PROPOSTA, @DT_PROPOSTA, 2)

SET @CD_PROPOSTA = SCOPE_IDENTITY()

IF @ID_SIT_FINAL = 3
BEGIN
    SET @DT_PAG = DATEADD(DAY, 1 + @CD_PROPOSTA % 3, @DT_PROPOSTA)
    IF @DT_PAG > GETDATE() SET @DT_PAG = @DT_PROPOSTA
    EXEC SP_EFETIVA_PROPOSTA @CD_PROPOSTA, @DT_PAG, @VL1, 2, @CD_COTA OUTPUT
END
GO

/* Vendas -------------------------------------------------------------------
   Vendedores ativos: 1..11 e 13. Bens por grupo:
     001041 -> 1..5   002087 -> 6..10   003012 -> 11..13
--------------------------------------------------------------------------- */
DECLARE @K INT, @R BIGINT, @DT DATETIME, @BEM INT, @VEND INT, @CD_PROPOSTA INT

SET @R = 777

-- 001041 Imoveis: 160 cotas entre 04/05 e 30/10/2026
SET @K = 1
WHILE @K <= 160
BEGIN
    SET @R = (@R * 1103515245 + 12345) % 2147483648
    SET @DT = DATEADD(MINUTE, CAST(540 + @R % 540 AS INT), DATEADD(DAY, (@K - 1) * 179 / 160, '20260504'))
    SET @BEM = CASE WHEN @R % 10 < 2 THEN 1 WHEN @R % 10 < 5 THEN 2 WHEN @R % 10 < 8 THEN 3 WHEN @R % 10 < 9 THEN 4 ELSE 5 END
    SET @VEND = (@R / 65536) % 12 + 1  IF @VEND = 12 SET @VEND = 13
    EXEC #VENDE 1, @K, @BEM, @VEND, @DT, 3
    SET @K = @K + 1
END

-- propostas canceladas no imoveis (desistiram antes de pagar)
EXEC #VENDE 1, 161, 3, 1, '20260612 10:15', 4
EXEC #VENDE 1, 162, 5, 6, '20260819 15:40', 4

EXEC SP_CONSTITUI_GRUPO 1, '20261218', 3

-- 002087 Veiculos: 63 cotas entre 03/08 e 14/11/2026 (consorciados 150..212; 150..160 ja tem imovel)
SET @K = 1
WHILE @K <= 63
BEGIN
    SET @R = (@R * 1103515245 + 12345) % 2147483648
    SET @DT = DATEADD(MINUTE, CAST(540 + @R % 540 AS INT), DATEADD(DAY, (@K - 1) * 103 / 63, '20260803'))
    SET @BEM = CASE WHEN @R % 10 < 2 THEN 6 WHEN @R % 10 < 5 THEN 7 WHEN @R % 10 < 8 THEN 8 WHEN @R % 10 < 9 THEN 9 ELSE 10 END
    SET @VEND = (@R / 65536) % 12 + 1  IF @VEND = 12 SET @VEND = 13
    SET @CD_PROPOSTA = @K + 149  -- reaproveita a variavel como codigo do consorciado
    EXEC #VENDE 2, @CD_PROPOSTA, @BEM, @VEND, @DT, 3
    SET @K = @K + 1
END

-- arrependimento: cota 064-0 vendida ha 3 dias, cancelada; numero revendido como 064-1
SET @DT = DATEADD(HOUR, 10, DATEADD(DAY, DATEDIFF(DAY, 0, GETDATE()) - 3, 0))
EXEC #VENDE 2, 213, 8, 4, @DT, 3, @CD_PROPOSTA OUTPUT
EXEC SP_ARREPENDIMENTO_PROPOSTA @CD_PROPOSTA, 2

SET @DT = DATEADD(HOUR, 14, DATEADD(DAY, DATEDIFF(DAY, 0, GETDATE()) - 2, 0))
EXEC #VENDE 2, 214, 7, 10, @DT, 3

-- propostas em andamento no veiculos
SET @DT = DATEADD(HOUR, 11, DATEADD(DAY, DATEDIFF(DAY, 0, GETDATE()) - 1, 0))
EXEC #VENDE 2, 215, 9, 2, @DT, 2
EXEC #VENDE 2, 216, 6, 13, @DT, 2
EXEC #VENDE 2, 217, 8, 5, @DT, 1
EXEC #VENDE 2, 218, 10, 7, '20260921 16:20', 4

-- 003012 Pesados: 5 cotas desde a abertura (09/11/2026)
EXEC #VENDE 3, 230, 12, 10, '20261109 09:30', 3
EXEC #VENDE 3, 231, 11, 11, '20261110 14:05', 3
EXEC #VENDE 3, 232, 13, 1,  '20261112 10:50', 3
EXEC #VENDE 3, 233, 12, 2,  '20261116 17:10', 3
EXEC #VENDE 3, 234, 11, 13, '20261118 11:25', 3
EXEC #VENDE 3, 235, 13, 10, '20261119 15:00', 2
GO

