/* ---------------------------------------------------------------------------
   Movimentacao do grupo (recursos segregados - Lei 11.795, art. 5o)
   SG_FUNDO: FC fundo comum, FR fundo de reserva, TA taxa de administracao,
             RD recursos a devolver
--------------------------------------------------------------------------- */
CREATE TABLE TB_GRUPO_MOVIMENTO (
    CD_MOVIMENTO        INT IDENTITY(1,1) NOT NULL,
    CD_GRUPO            INT          NOT NULL,
    SG_FUNDO            CHAR(2)      NOT NULL,
    ID_TIPO_MOVIMENTO   SMALLINT     NOT NULL,      -- ver TB_DOMINIO 'TIPO_MOVIMENTO'
    DT_MOVIMENTO        DATETIME     NOT NULL,
    VL_MOVIMENTO        MONEY        NOT NULL,      -- positivo entra, negativo sai
    CD_COTA             INT          NULL,
    CD_PARCELA          INT          NULL,
    CD_PROPOSTA         INT          NULL,
    DS_HISTORICO        VARCHAR(200) NULL,
    CD_USUARIO          INT          NULL,
    DT_CADASTRO         DATETIME     NOT NULL CONSTRAINT DF_MOV_DT DEFAULT GETDATE(),
    CONSTRAINT PK_GRUPO_MOVIMENTO PRIMARY KEY (CD_MOVIMENTO),
    CONSTRAINT FK_MOV_GRUPO FOREIGN KEY (CD_GRUPO) REFERENCES TB_GRUPO (CD_GRUPO),
    CONSTRAINT FK_MOV_COTA FOREIGN KEY (CD_COTA) REFERENCES TB_COTA (CD_COTA),
    CONSTRAINT FK_MOV_PARCELA FOREIGN KEY (CD_PARCELA) REFERENCES TB_PARCELA (CD_PARCELA),
    CONSTRAINT CK_MOV_FUNDO CHECK (SG_FUNDO IN ('FC','FR','TA','RD'))
