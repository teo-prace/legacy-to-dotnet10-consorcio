CREATE TABLE TB_LANCE (
    CD_LANCE            INT IDENTITY(1,1) NOT NULL,
    CD_ASSEMBLEIA       INT          NOT NULL,
    CD_COTA             INT          NOT NULL,
    ID_TIPO_LANCE       TINYINT      NOT NULL,      -- 1 livre, 2 fixo
    PC_LANCE            DECIMAL(9,4) NOT NULL,
    PC_EMBUTIDO         DECIMAL(9,4) NOT NULL CONSTRAINT DF_LANCE_EMB DEFAULT 0,
    DT_REGISTRO         DATETIME     NOT NULL CONSTRAINT DF_LANCE_DT DEFAULT GETDATE(),
    CD_USUARIO          INT          NULL,
    ID_SITUACAO         TINYINT      NOT NULL CONSTRAINT DF_LANCE_SIT DEFAULT 1, -- 1 registrado, 2 vencedor, 3 nao contemplado, 4 desclassificado, 5 cancelado
    DS_MOTIVO           VARCHAR(200) NULL,
    NR_ORDEM            SMALLINT     NULL,          -- ordem na apuracao
    CONSTRAINT PK_LANCE PRIMARY KEY (CD_LANCE),
    CONSTRAINT UQ_LANCE_AGO_COTA UNIQUE (CD_ASSEMBLEIA, CD_COTA),
    CONSTRAINT FK_LANCE_AGO FOREIGN KEY (CD_ASSEMBLEIA) REFERENCES TB_ASSEMBLEIA (CD_ASSEMBLEIA),
    CONSTRAINT FK_LANCE_COTA FOREIGN KEY (CD_COTA) REFERENCES TB_COTA (CD_COTA)
)
GO

CREATE TABLE TB_CONTEMPLACAO (
    CD_CONTEMPLACAO      INT IDENTITY(1,1) NOT NULL,
    CD_COTA              INT          NOT NULL,
    CD_ASSEMBLEIA        INT          NOT NULL,
    ID_TIPO              TINYINT      NOT NULL,     -- 1 sorteio, 2 lance, 3 devolucao (excluida/desistente)
    CD_LANCE             INT          NULL,
    VL_CREDITO           MONEY        NOT NULL,
    PC_LANCE             DECIMAL(9,4) NOT NULL CONSTRAINT DF_CONT_PCL DEFAULT 0,
    VL_LANCE             MONEY        NOT NULL CONSTRAINT DF_CONT_VLL DEFAULT 0,
    VL_EMBUTIDO          MONEY        NOT NULL CONSTRAINT DF_CONT_EMB DEFAULT 0,
    VL_RECURSOS_PROPRIOS MONEY        NOT NULL CONSTRAINT DF_CONT_REC DEFAULT 0,
    VL_DESCONTO          MONEY        NOT NULL CONSTRAINT DF_CONT_DESC DEFAULT 0, -- multa rescisoria (devolucao)
    VL_CREDITO_LIQUIDO   MONEY        NOT NULL,
    ID_SITUACAO          TINYINT      NOT NULL CONSTRAINT DF_CONT_SIT DEFAULT 1, -- 1 aguardando liberacao, 2 liberado, 3 cancelada
    DT_CONTEMPLACAO      DATETIME     NOT NULL,
    DT_LIBERACAO         DATETIME     NULL,
    DS_FAVORECIDO        VARCHAR(150) NULL,
    CD_USUARIO_LIBERACAO INT          NULL,
    CONSTRAINT PK_CONTEMPLACAO PRIMARY KEY (CD_CONTEMPLACAO),
    CONSTRAINT FK_CONT_COTA FOREIGN KEY (CD_COTA) REFERENCES TB_COTA (CD_COTA),
    CONSTRAINT FK_CONT_AGO FOREIGN KEY (CD_ASSEMBLEIA) REFERENCES TB_ASSEMBLEIA (CD_ASSEMBLEIA),
    CONSTRAINT FK_CONT_LANCE FOREIGN KEY (CD_LANCE) REFERENCES TB_LANCE (CD_LANCE)
)
GO
