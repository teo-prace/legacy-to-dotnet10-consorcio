IF OBJECT_ID('SP_AGENDA_ASSEMBLEIA') IS NOT NULL DROP PROCEDURE SP_AGENDA_ASSEMBLEIA
GO
/*****************************************************************************
  Agenda a proxima assembleia (AGO) do grupo.
  - 1a AGO: data da constituicao
  - demais: dia de assembleia do grupo no mes seguinte ao da ultima AGO
  - so uma AGO agendada por vez
  - lances ate a vespera
  2014-08 J.P.
*****************************************************************************/
CREATE PROCEDURE SP_AGENDA_ASSEMBLEIA
    @CD_GRUPO       INT,
    @DT_ASSEMBLEIA  DATETIME = NULL,
    @CD_USUARIO     INT,
    @CD_ASSEMBLEIA  INT = NULL OUTPUT
AS
SET NOCOUNT ON

DECLARE @ID_SIT TINYINT, @NR_GRUPO CHAR(6), @DT_CONST DATETIME, @DIA TINYINT,
        @NR SMALLINT, @DT_ULTIMA DATETIME, @MSG VARCHAR(200)

SELECT @ID_SIT = ID_SITUACAO, @NR_GRUPO = NR_GRUPO, @DT_CONST = DT_CONSTITUICAO, @DIA = NR_DIA_ASSEMBLEIA
  FROM TB_GRUPO WHERE CD_GRUPO = @CD_GRUPO

IF @ID_SIT IS NULL OR @ID_SIT <> 2
BEGIN
    RAISERROR('Grupo nao esta em andamento.', 16, 1)
    RETURN 1
END

IF EXISTS (SELECT 1 FROM TB_ASSEMBLEIA WHERE CD_GRUPO = @CD_GRUPO AND ID_SITUACAO = 1)
BEGIN
    RAISERROR('Ja existe assembleia agendada para o grupo %s.', 16, 1, @NR_GRUPO)
    RETURN 1
END

SELECT @NR = ISNULL(MAX(NR_ASSEMBLEIA), 0) + 1,
       @DT_ULTIMA = MAX(DT_ASSEMBLEIA)
  FROM TB_ASSEMBLEIA WHERE CD_GRUPO = @CD_GRUPO

IF @DT_ASSEMBLEIA IS NULL
BEGIN
    IF @NR = 1
        SET @DT_ASSEMBLEIA = @DT_CONST
    ELSE
        SET @DT_ASSEMBLEIA = DATEADD(DAY, @DIA - 1, DATEADD(MONTH, DATEDIFF(MONTH, 0, @DT_ULTIMA) + 1, 0))
END
SET @DT_ASSEMBLEIA = DATEADD(DAY, DATEDIFF(DAY, 0, @DT_ASSEMBLEIA), 0)

IF @DT_ULTIMA IS NOT NULL AND @DT_ASSEMBLEIA <= @DT_ULTIMA
BEGIN
    RAISERROR('Data anterior a ultima assembleia do grupo.', 16, 1)
    RETURN 1
END

INSERT INTO TB_ASSEMBLEIA (CD_GRUPO, NR_ASSEMBLEIA, DT_ASSEMBLEIA, DT_LIMITE_LANCE, ID_SITUACAO)
VALUES (@CD_GRUPO, @NR, @DT_ASSEMBLEIA, DATEADD(DAY, -1, @DT_ASSEMBLEIA), 1)

IF @@ERROR <> 0
BEGIN
    RAISERROR('Erro ao agendar assembleia.', 16, 1)
    RETURN 1
END

SET @CD_ASSEMBLEIA = @@IDENTITY
SET @MSG = 'Grupo ' + @NR_GRUPO + ' AGO ' + CAST(@NR AS VARCHAR) + ' em ' + CONVERT(VARCHAR(10), @DT_ASSEMBLEIA, 103)
EXEC SP_GRAVA_LOG @CD_USUARIO, 'AGENDA_ASSEMBLEIA', @MSG
RETURN 0
GO
