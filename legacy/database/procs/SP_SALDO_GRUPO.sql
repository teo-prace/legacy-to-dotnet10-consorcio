IF OBJECT_ID('SP_SALDO_GRUPO') IS NOT NULL DROP PROCEDURE SP_SALDO_GRUPO
GO
/*
  Saldo por fundo do grupo.
  2016-09 J.P.
*/
CREATE PROCEDURE SP_SALDO_GRUPO
    @CD_GRUPO      INT,
    @DT_REFERENCIA DATETIME = NULL
AS
SET NOCOUNT ON

IF @DT_REFERENCIA IS NULL SET @DT_REFERENCIA = GETDATE()

SELECT F.SG_FUNDO,
       F.NM_FUNDO,
       ISNULL((SELECT SUM(M.VL_MOVIMENTO)
                 FROM TB_GRUPO_MOVIMENTO M
                WHERE M.CD_GRUPO = @CD_GRUPO
                  AND M.SG_FUNDO = F.SG_FUNDO
                  AND M.DT_MOVIMENTO <= @DT_REFERENCIA), 0) AS VL_SALDO
  FROM (SELECT 'FC' AS SG_FUNDO, 'Fundo comum' AS NM_FUNDO, 1 AS ORDEM
        UNION ALL SELECT 'FR', 'Fundo de reserva', 2
        UNION ALL SELECT 'TA', 'Taxa de administracao', 3
        UNION ALL SELECT 'RD', 'Recursos a devolver', 4) F
 ORDER BY F.ORDEM
GO
