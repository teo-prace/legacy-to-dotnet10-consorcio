IF OBJECT_ID('FN_VALOR_BEM') IS NOT NULL DROP FUNCTION FN_VALOR_BEM
GO
/*
  Valor do bem vigente na data informada.
  2005-03 R.A.
*/
CREATE FUNCTION FN_VALOR_BEM (@CD_BEM INT, @DT DATETIME)
RETURNS MONEY
AS
BEGIN
    DECLARE @VL MONEY

    SELECT TOP 1 @VL = VL_BEM
      FROM TB_BEM_VALOR
     WHERE CD_BEM = @CD_BEM
       AND DT_VIGENCIA <= @DT
     ORDER BY DT_VIGENCIA DESC

    RETURN @VL
END
GO
