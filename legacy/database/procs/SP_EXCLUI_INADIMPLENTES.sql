IF OBJECT_ID('SP_EXCLUI_INADIMPLENTES') IS NOT NULL DROP PROCEDURE SP_EXCLUI_INADIMPLENTES
GO
/*****************************************************************************
  Exclusao de cotas inadimplentes (batch diario).

  Cota ATIVA nao contemplada com QT_PARCELAS_EXCLUSAO (3) ou mais parcelas
  vencidas em aberto (prazo sem encargos ja passou) -> excluida; parcelas
  em aberto canceladas. O que foi pago fica no fundo comum (devolucao quando
  sorteada - ver SP_APURA_ASSEMBLEIA).

  Retorna:
    1. cotas excluidas
    2. contempladas inadimplentes (nao sao excluidas: cobranca juridica)

  2006-02 R.A.
  2016-02 J.P. chamada pelo SGC.Batch (antes: job do SQL Agent)
*****************************************************************************/
CREATE PROCEDURE SP_EXCLUI_INADIMPLENTES
    @DT_REFERENCIA DATETIME = NULL,
    @CD_USUARIO    INT
AS
SET NOCOUNT ON

DECLARE @DIA DATETIME, @QT INT, @MSG VARCHAR(300), @CD_COTA INT, @DS VARCHAR(200)

IF @DT_REFERENCIA IS NULL SET @DT_REFERENCIA = GETDATE()
SET @DIA = DATEADD(DAY, DATEDIFF(DAY, 0, @DT_REFERENCIA), 0)
SELECT @QT = CAST(DS_VALOR AS INT) FROM TB_PARAMETRO WHERE NM_PARAMETRO = 'QT_PARCELAS_EXCLUSAO'
IF @QT IS NULL SET @QT = 3

CREATE TABLE #VENCIDAS (CD_COTA INT PRIMARY KEY, QT_VENCIDAS INT, VL_ABERTO MONEY)

INSERT INTO #VENCIDAS (CD_COTA, QT_VENCIDAS, VL_ABERTO)
SELECT P.CD_COTA, COUNT(*), SUM(ISNULL(P.VL_PARCELA, 0))
  FROM TB_PARCELA P
 INNER JOIN TB_COTA C ON C.CD_COTA = P.CD_COTA
 WHERE C.ID_SITUACAO IN (1, 2)
   AND P.ID_SITUACAO IN (1, 2)
   AND P.DT_VENCIMENTO < @DIA
   AND dbo.FN_PROXIMO_DIA_UTIL(P.DT_VENCIMENTO) < @DIA
 GROUP BY P.CD_COTA

SELECT V.CD_COTA, V.QT_VENCIDAS
  INTO #EXCLUIR
  FROM #VENCIDAS V INNER JOIN TB_COTA C ON C.CD_COTA = V.CD_COTA
 WHERE C.ID_SITUACAO = 1 AND V.QT_VENCIDAS >= @QT

BEGIN TRANSACTION

UPDATE TB_PARCELA SET ID_SITUACAO = 4
 WHERE CD_COTA IN (SELECT CD_COTA FROM #EXCLUIR) AND ID_SITUACAO IN (1, 2)
IF @@ERROR <> 0 BEGIN SET @MSG = 'Erro ao cancelar parcelas.' GOTO ERRO END

UPDATE TB_COTA SET ID_SITUACAO = 3, DT_SITUACAO = @DT_REFERENCIA
 WHERE CD_COTA IN (SELECT CD_COTA FROM #EXCLUIR)
IF @@ERROR <> 0 BEGIN SET @MSG = 'Erro ao excluir cotas.' GOTO ERRO END

DECLARE C_LOG CURSOR LOCAL FAST_FORWARD FOR
    SELECT E.CD_COTA, G.NR_GRUPO + '/' + RIGHT('000' + CAST(C.NR_COTA AS VARCHAR), 3) + '-' + CAST(C.NR_VERSAO AS VARCHAR)
           + ' - ' + CAST(E.QT_VENCIDAS AS VARCHAR) + ' parcelas vencidas'
      FROM #EXCLUIR E INNER JOIN TB_COTA C ON C.CD_COTA = E.CD_COTA INNER JOIN TB_GRUPO G ON G.CD_GRUPO = C.CD_GRUPO
OPEN C_LOG
FETCH NEXT FROM C_LOG INTO @CD_COTA, @DS
WHILE @@FETCH_STATUS = 0
BEGIN
    EXEC SP_GRAVA_LOG @CD_USUARIO, 'EXCLUSAO_COTA', @DS
    FETCH NEXT FROM C_LOG INTO @CD_COTA, @DS
END
CLOSE C_LOG
DEALLOCATE C_LOG

COMMIT TRANSACTION

SELECT G.NR_GRUPO, C.NR_COTA, C.NR_VERSAO, X.NM_CONSORCIADO, E.QT_VENCIDAS, C.PC_AMORTIZADO
  FROM #EXCLUIR E INNER JOIN TB_COTA C ON C.CD_COTA = E.CD_COTA
 INNER JOIN TB_GRUPO G ON G.CD_GRUPO = C.CD_GRUPO INNER JOIN TB_CONSORCIADO X ON X.CD_CONSORCIADO = C.CD_CONSORCIADO
 ORDER BY G.NR_GRUPO, C.NR_COTA

SELECT G.NR_GRUPO, C.NR_COTA, C.NR_VERSAO, X.NM_CONSORCIADO, V.QT_VENCIDAS, V.VL_ABERTO
  FROM #VENCIDAS V INNER JOIN TB_COTA C ON C.CD_COTA = V.CD_COTA
 INNER JOIN TB_GRUPO G ON G.CD_GRUPO = C.CD_GRUPO INNER JOIN TB_CONSORCIADO X ON X.CD_CONSORCIADO = C.CD_CONSORCIADO
 WHERE C.ID_SITUACAO = 2
 ORDER BY V.QT_VENCIDAS DESC, G.NR_GRUPO, C.NR_COTA

RETURN 0

ERRO:
IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION
RAISERROR(@MSG, 16, 1)
RETURN 1
GO
