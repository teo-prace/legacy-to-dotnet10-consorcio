IF OBJECT_ID('TR_PLANO_ATUALIZA_GRUPO') IS NOT NULL DROP TRIGGER TR_PLANO_ATUALIZA_GRUPO
GO
/*
  2012-06 M.S. - chamado 4471 (comercial)
  Ao alterar as taxas do plano, os grupos ainda em formacao acompanham,
  para nao precisar abrir grupo novo a cada campanha.
*/
CREATE TRIGGER TR_PLANO_ATUALIZA_GRUPO ON TB_PLANO
AFTER UPDATE
AS
SET NOCOUNT ON

IF UPDATE(PC_TAXA_ADM) OR UPDATE(PC_ANTECIPACAO_TA) OR UPDATE(PC_FUNDO_RESERVA)
BEGIN
    UPDATE G
       SET PC_TAXA_ADM       = I.PC_TAXA_ADM,
           PC_ANTECIPACAO_TA = I.PC_ANTECIPACAO_TA,
           PC_FUNDO_RESERVA  = I.PC_FUNDO_RESERVA
      FROM TB_GRUPO G
     INNER JOIN inserted I ON I.CD_PLANO = G.CD_PLANO
     WHERE G.ID_SITUACAO = 1
END
GO
