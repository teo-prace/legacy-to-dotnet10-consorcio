IF OBJECT_ID('SP_LIBERA_CREDITO') IS NOT NULL DROP PROCEDURE SP_LIBERA_CREDITO
GO
/*****************************************************************************
  Liberacao do credito do contemplado (pagamento ao vendedor do bem).
  Debita o credito liquido (credito - embutido) do fundo comum.
  2005-09 R.A.
  2014-08 J.P. a partir de TB_CONTEMPLACAO
  2016-11 J.P. devolucao a excluidos/desistentes (tipo 3): favorecido = consorciado
*****************************************************************************/
CREATE PROCEDURE SP_LIBERA_CREDITO
    @CD_CONTEMPLACAO INT,
    @DT_LIBERACAO    DATETIME,
    @DS_FAVORECIDO   VARCHAR(150),
    @CD_USUARIO      INT
AS
SET NOCOUNT ON

DECLARE @ID_SIT TINYINT, @ID_TIPO TINYINT, @CD_COTA INT, @CD_GRUPO INT, @VL MONEY, @DT_CONT DATETIME,
        @NR_COTA SMALLINT, @NR_VERSAO TINYINT, @SALDO MONEY, @MSG VARCHAR(200)

SELECT @ID_SIT = T.ID_SITUACAO, @ID_TIPO = T.ID_TIPO, @CD_COTA = T.CD_COTA, @VL = T.VL_CREDITO_LIQUIDO, @DT_CONT = T.DT_CONTEMPLACAO,
       @CD_GRUPO = C.CD_GRUPO, @NR_COTA = C.NR_COTA, @NR_VERSAO = C.NR_VERSAO
  FROM TB_CONTEMPLACAO T
 INNER JOIN TB_COTA C ON C.CD_COTA = T.CD_COTA
 WHERE T.CD_CONTEMPLACAO = @CD_CONTEMPLACAO

IF @ID_SIT IS NULL OR @ID_SIT <> 1
BEGIN
    RAISERROR('Contemplacao nao esta aguardando liberacao.', 16, 1)
    RETURN 1
END

IF @DT_LIBERACAO < @DT_CONT
BEGIN
    RAISERROR('Data de liberacao anterior a contemplacao.', 16, 1)
    RETURN 1
END

IF ISNULL(LTRIM(@DS_FAVORECIDO), '') = ''
BEGIN
    RAISERROR('Informe o favorecido (vendedor do bem).', 16, 1)
    RETURN 1
END

SELECT @SALDO = ISNULL(SUM(VL_MOVIMENTO), 0)
  FROM TB_GRUPO_MOVIMENTO WHERE CD_GRUPO = @CD_GRUPO AND SG_FUNDO = 'FC' AND DT_MOVIMENTO <= @DT_LIBERACAO

IF @SALDO < @VL
BEGIN
    RAISERROR('Saldo do fundo comum insuficiente na data.', 16, 1)
    RETURN 1
END

BEGIN TRANSACTION

INSERT INTO TB_GRUPO_MOVIMENTO (CD_GRUPO, SG_FUNDO, ID_TIPO_MOVIMENTO, DT_MOVIMENTO, VL_MOVIMENTO, CD_COTA, DS_HISTORICO, CD_USUARIO)
VALUES (@CD_GRUPO, 'FC', CASE WHEN @ID_TIPO = 3 THEN 5 ELSE 3 END, @DT_LIBERACAO, -@VL, @CD_COTA,
        CASE WHEN @ID_TIPO = 3 THEN 'Devolucao' ELSE 'Credito' END + ' - cota ' + RIGHT('000' + CAST(@NR_COTA AS VARCHAR), 3) + '-' + CAST(@NR_VERSAO AS VARCHAR)
        + ' - ' + LEFT(@DS_FAVORECIDO, 120), @CD_USUARIO)
IF @@ERROR <> 0 BEGIN SET @MSG = 'Erro no lancamento do credito.' GOTO ERRO END

UPDATE TB_CONTEMPLACAO
   SET ID_SITUACAO = 2, DT_LIBERACAO = @DT_LIBERACAO, DS_FAVORECIDO = @DS_FAVORECIDO, CD_USUARIO_LIBERACAO = @CD_USUARIO
 WHERE CD_CONTEMPLACAO = @CD_CONTEMPLACAO
IF @@ERROR <> 0 BEGIN SET @MSG = 'Erro ao atualizar contemplacao.' GOTO ERRO END

COMMIT TRANSACTION
RETURN 0

ERRO:
IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION
RAISERROR(@MSG, 16, 1)
RETURN 1
GO
