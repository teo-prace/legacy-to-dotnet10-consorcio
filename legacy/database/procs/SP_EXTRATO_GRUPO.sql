IF OBJECT_ID('SP_EXTRATO_GRUPO') IS NOT NULL DROP PROCEDURE SP_EXTRATO_GRUPO
GO
/*
  Extrato de movimentacao do grupo com saldo acumulado por fundo.
  2016-09 J.P.
  2018-03 J.P. filtro por fundo
*/
CREATE PROCEDURE SP_EXTRATO_GRUPO
    @CD_GRUPO INT,
    @SG_FUNDO CHAR(2)  = NULL,
    @DT_INI   DATETIME = NULL,
    @DT_FIM   DATETIME = NULL
AS
SET NOCOUNT ON

IF @DT_INI IS NULL SET @DT_INI = '19000101'
IF @DT_FIM IS NULL SET @DT_FIM = GETDATE()

-- fim do dia
SET @DT_FIM = DATEADD(MS, -3, DATEADD(DAY, 1, DATEADD(DAY, DATEDIFF(DAY, 0, @DT_FIM), 0)))

SELECT M.CD_MOVIMENTO,
       M.DT_MOVIMENTO,
       M.SG_FUNDO,
       D.DS_VALOR AS DS_TIPO_MOVIMENTO,
       M.DS_HISTORICO,
       M.VL_MOVIMENTO,
       (SELECT SUM(M2.VL_MOVIMENTO)
          FROM TB_GRUPO_MOVIMENTO M2
         WHERE M2.CD_GRUPO = M.CD_GRUPO
           AND M2.SG_FUNDO = M.SG_FUNDO
           AND (M2.DT_MOVIMENTO < M.DT_MOVIMENTO
                OR (M2.DT_MOVIMENTO = M.DT_MOVIMENTO AND M2.CD_MOVIMENTO <= M.CD_MOVIMENTO))) AS VL_SALDO_FUNDO
  FROM TB_GRUPO_MOVIMENTO M
  LEFT JOIN TB_DOMINIO D ON D.NM_DOMINIO = 'TIPO_MOVIMENTO' AND D.CD_VALOR = CAST(M.ID_TIPO_MOVIMENTO AS VARCHAR)
 WHERE M.CD_GRUPO = @CD_GRUPO
   AND (@SG_FUNDO IS NULL OR M.SG_FUNDO = @SG_FUNDO)
   AND M.DT_MOVIMENTO BETWEEN @DT_INI AND @DT_FIM
 ORDER BY M.DT_MOVIMENTO, M.CD_MOVIMENTO
GO
