IF OBJECT_ID('SP_INCLUI_CONSORCIADO') IS NOT NULL DROP PROCEDURE SP_INCLUI_CONSORCIADO
GO
/*
  Cadastro rapido de consorciado (usado na digitacao da proposta).
  Se o CPF ja existe, devolve o codigo existente sem alterar o cadastro.
  O cadastro completo e feito na tela de consorciados.

  2011-06 M.S.
*/
CREATE PROCEDURE SP_INCLUI_CONSORCIADO
    @NR_CPF          CHAR(11),
    @NM_CONSORCIADO  VARCHAR(120),
    @DT_NASCIMENTO   DATETIME     = NULL,
    @DS_EMAIL        VARCHAR(100) = NULL,
    @NR_CELULAR      VARCHAR(20)  = NULL,
    @NM_CIDADE       VARCHAR(60)  = NULL,
    @SG_UF           CHAR(2)      = NULL,
    @VL_RENDA_MENSAL MONEY        = NULL,
    @CD_USUARIO      INT,
    @CD_CONSORCIADO  INT OUTPUT
AS
SET NOCOUNT ON

IF dbo.FN_CPF_VALIDO(@NR_CPF) = 0
BEGIN
    RAISERROR('CPF invalido.', 16, 1)
    RETURN 1
END

SELECT @CD_CONSORCIADO = CD_CONSORCIADO
  FROM TB_CONSORCIADO
 WHERE NR_CPF = @NR_CPF

IF @CD_CONSORCIADO IS NOT NULL
    RETURN 0

INSERT INTO TB_CONSORCIADO (NR_CPF, NM_CONSORCIADO, DT_NASCIMENTO, DS_EMAIL, NR_CELULAR,
                            NM_CIDADE, SG_UF, VL_RENDA_MENSAL, CD_USUARIO_CADASTRO)
VALUES (@NR_CPF, UPPER(@NM_CONSORCIADO), @DT_NASCIMENTO, @DS_EMAIL, @NR_CELULAR,
        @NM_CIDADE, @SG_UF, @VL_RENDA_MENSAL, @CD_USUARIO)

IF @@ERROR <> 0
BEGIN
    RAISERROR('Erro ao incluir consorciado.', 16, 1)
    RETURN 1
END

SET @CD_CONSORCIADO = @@IDENTITY
RETURN 0
GO
