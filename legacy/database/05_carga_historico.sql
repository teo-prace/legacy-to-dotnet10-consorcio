 SGC - carga de historico (ambiente de desenvolvimento/homologacao)

 Grupo 002071 (Veiculo leve 60 meses, regulamento 2024.1):
   - 80 cotas vendidas entre 03/2024 e 06/2024
   - constituido com 1a assembleia em 25/06/2024
   - emissao mensal (dia 5) e pagamentos de 07/2024 a 11/2026, usando as
     procedures do sistema (SP_EMITE_COBRANCA, SP_BAIXA_PARCELA)

 Pagamentos: a data de cada pagamento e planejada na emissao e executada
 em ordem cronologica (pontos de corte), para que processos datados
 (assembleia) enxerguem so o que ja tinha sido pago na data.

 Perfil (deterministico):
   ~85% em dia, ~10% com atraso de 1 a 25 dias (multa/juros), ~3% pagam a
   maior, ~2% com atraso de 35 a 45 dias. Cotas 007, 023, 041 param de
   pagar em 07/2026; 058 e 066 em 09/2026; 012 em 10/2026.
 Data de referencia da carga: 20/11/2026 (pagamentos depois disso ficam
 em aberto).
