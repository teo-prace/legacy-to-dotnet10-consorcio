CREATE PROCEDURE #VENDE
    @CD_GRUPO       INT,
    @CD_CONSORCIADO INT,
    @CD_BEM         INT,
    @CD_VENDEDOR    INT,
    @DT_PROPOSTA    DATETIME
AS
SET NOCOUNT ON
DECLARE @N SMALLINT, @TA DECIMAL(9,4), @ANT DECIMAL(9,4), @FR DECIMAL(9,4), @CD_PLANO INT,
        @VL_BEM MONEY, @PC1 DECIMAL(9,6), @VL1 MONEY, @CD_PV INT, @NR VARCHAR(12), @CD_COTA INT,
        @DT_PAG DATETIME, @CD_PROPOSTA INT

SELECT @N = QT_PRAZO_MESES - QT_ASSEMBLEIAS_REALIZADAS, @TA = PC_TAXA_ADM, @ANT = PC_ANTECIPACAO_TA,
       @FR = PC_FUNDO_RESERVA, @CD_PLANO = CD_PLANO
  FROM TB_GRUPO WHERE CD_GRUPO = @CD_GRUPO

SET @PC1 = ROUND(100.0 / @N, 6) + ROUND((@TA - @ANT) / @N, 6) + @ANT + ROUND(@FR / @N, 6)
SET @VL_BEM = dbo.FN_VALOR_BEM(@CD_BEM, @DT_PROPOSTA)
SET @VL1 = ROUND(@VL_BEM * @PC1 / 100, 2)
SELECT @CD_PV = CD_PONTO_VENDA FROM TB_VENDEDOR WHERE CD_VENDEDOR = @CD_VENDEDOR

SELECT @NR = CAST(YEAR(@DT_PROPOSTA) AS VARCHAR) + '-' + RIGHT('000000' + CAST(COUNT(*) + 1 AS VARCHAR), 6)
  FROM TB_PROPOSTA WHERE NR_PROPOSTA LIKE CAST(YEAR(@DT_PROPOSTA) AS VARCHAR) + '-%'

INSERT INTO TB_PROPOSTA (NR_PROPOSTA, CD_CONSORCIADO, CD_PLANO, CD_GRUPO, CD_BEM, CD_PONTO_VENDA, CD_VENDEDOR,
                         DT_PROPOSTA, DT_ASSINATURA, VL_BEM_PROPOSTA, VL_PRIMEIRA_PARCELA, ID_SITUACAO, DT_SITUACAO,
                         DT_CADASTRO, CD_USUARIO_CADASTRO)
VALUES (@NR, @CD_CONSORCIADO, @CD_PLANO, @CD_GRUPO, @CD_BEM, @CD_PV, @CD_VENDEDOR,
        @DT_PROPOSTA, @DT_PROPOSTA, @VL_BEM, @VL1, 2, @DT_PROPOSTA, @DT_PROPOSTA, 2)

SET @CD_PROPOSTA = SCOPE_IDENTITY()
SET @DT_PAG = DATEADD(DAY, 1 + @CD_PROPOSTA % 3, @DT_PROPOSTA)
EXEC SP_EFETIVA_PROPOSTA @CD_PROPOSTA, @DT_PAG, @VL1, 2, @CD_COTA OUTPUT
GO

/* Pagamentos planejados e execucao ate um ponto de corte ------------------ */
CREATE TABLE #PAGTO_PLANEJADO (
    CD_PARCELA   INT PRIMARY KEY,
    DT_PAGAMENTO DATETIME,
    VL_PAGO      MONEY,
    VL_MULTA     MONEY,
    VL_JUROS     MONEY,
    ID_ORIGEM    TINYINT,
    FL_BAIXADO   CHAR(1) DEFAULT 'N'
)
GO

CREATE PROCEDURE #PLANEJA_PAGAMENTOS
    @NR_ANO_MES INT
AS
SET NOCOUNT ON
DECLARE @DT_CORTE DATETIME
SET @DT_CORTE = '20261120 23:59'

INSERT INTO #PAGTO_PLANEJADO (CD_PARCELA, DT_PAGAMENTO, VL_PAGO, VL_MULTA, VL_JUROS, ID_ORIGEM)
SELECT X.CD_PARCELA, X.DT_PAG,
       X.VL_PARCELA + X.MULTA + X.JUROS + X.EXCEDENTE, X.MULTA, X.JUROS,
       CASE WHEN X.H % 5 = 0 THEN 1 ELSE 2 END
  FROM (SELECT Y.*,
               CASE WHEN Y.DT_PAG <= dbo.FN_PROXIMO_DIA_UTIL(Y.DT_VENCIMENTO) THEN 0 ELSE ROUND(Y.VL_PARCELA * 0.02, 2) END AS MULTA,
               CASE WHEN Y.DT_PAG <= dbo.FN_PROXIMO_DIA_UTIL(Y.DT_VENCIMENTO) THEN 0
                    ELSE ROUND(Y.VL_PARCELA * 0.01 / 30 * DATEDIFF(DAY, Y.DT_VENCIMENTO, Y.DT_PAG), 2) END AS JUROS
          FROM (SELECT P.CD_PARCELA, P.DT_VENCIMENTO, P.VL_PARCELA, Z.H,
                       CASE WHEN Z.H < 85 THEN DATEADD(DAY, -(Z.H % 4), P.DT_VENCIMENTO)
                            WHEN Z.H < 95 THEN DATEADD(DAY, 1 + Z.H % 25, P.DT_VENCIMENTO)
                            WHEN Z.H < 98 THEN DATEADD(DAY, -(Z.H % 3), P.DT_VENCIMENTO)
                            ELSE DATEADD(DAY, 35 + Z.H % 11, P.DT_VENCIMENTO) END AS DT_PAG,
                       CASE WHEN Z.H BETWEEN 95 AND 97 THEN 0.50 + (Z.H % 7) * 1.25 ELSE 0 END AS EXCEDENTE
                  FROM TB_PARCELA P
                 INNER JOIN TB_COTA C ON C.CD_COTA = P.CD_COTA
                 CROSS APPLY (SELECT ABS(CAST(HASHBYTES('MD5', CAST(P.CD_PARCELA AS VARCHAR) + '-' + CAST(@NR_ANO_MES AS VARCHAR)) AS INT)) % 100 AS H) Z
                 WHERE C.CD_GRUPO = 4
                   AND P.ID_SITUACAO = 2
                   AND YEAR(P.DT_VENCIMENTO) * 100 + MONTH(P.DT_VENCIMENTO) = @NR_ANO_MES
                   AND NOT (C.NR_COTA IN (7, 23, 41) AND @NR_ANO_MES >= 202607)
                   AND NOT (C.NR_COTA IN (58, 66)    AND @NR_ANO_MES >= 202609)
                   AND NOT (C.NR_COTA = 12           AND @NR_ANO_MES >= 202610)
                   AND NOT EXISTS (SELECT 1 FROM #PAGTO_PLANEJADO J WHERE J.CD_PARCELA = P.CD_PARCELA)) Y
       ) X
 WHERE X.DT_PAG <= @DT_CORTE
GO

CREATE PROCEDURE #EXECUTA_PAGAMENTOS
    @DT_ATE DATETIME
AS
SET NOCOUNT ON
DECLARE @CD_PARCELA INT, @DT DATETIME, @PAGO MONEY, @MULTA MONEY, @JUROS MONEY, @ORIGEM TINYINT, @USU INT

DECLARE C CURSOR LOCAL FAST_FORWARD FOR
    SELECT CD_PARCELA, DT_PAGAMENTO, VL_PAGO, VL_MULTA, VL_JUROS, ID_ORIGEM
      FROM #PAGTO_PLANEJADO
     WHERE FL_BAIXADO = 'N' AND DT_PAGAMENTO <= @DT_ATE
     ORDER BY DT_PAGAMENTO, CD_PARCELA
OPEN C
FETCH NEXT FROM C INTO @CD_PARCELA, @DT, @PAGO, @MULTA, @JUROS, @ORIGEM
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @USU = CASE WHEN @ORIGEM = 1 THEN 2 ELSE 1 END
    EXEC SP_BAIXA_PARCELA @CD_PARCELA, @DT, @PAGO, @MULTA, @JUROS, @ORIGEM, @USU
    UPDATE #PAGTO_PLANEJADO SET FL_BAIXADO = 'S' WHERE CD_PARCELA = @CD_PARCELA
    FETCH NEXT FROM C INTO @CD_PARCELA, @DT, @PAGO, @MULTA, @JUROS, @ORIGEM
END
CLOSE C
DEALLOCATE C
GO

/* Assembleia do mes: agenda, premios, lances e (opcional) apuracao ----------- */
CREATE PROCEDURE #REALIZA_AGO
    @CD_GRUPO INT,
    @APURAR   BIT
AS
SET NOCOUNT ON
DECLARE @CD_AGO INT, @NR SMALLINT, @DT DATETIME, @DT_LANCE DATETIME, @DT_APUR DATETIME,
        @CD_COTA INT, @PC DECIMAL(9,4), @EMB DECIMAL(9,4), @H INT

EXEC SP_AGENDA_ASSEMBLEIA @CD_GRUPO, NULL, 3, @CD_AGO OUTPUT
SELECT @NR = NR_ASSEMBLEIA, @DT = DT_ASSEMBLEIA FROM TB_ASSEMBLEIA WHERE CD_ASSEMBLEIA = @CD_AGO
SET @DT_LANCE = DATEADD(HOUR, -34, @DT)      -- antevespera, 14h
IF @APURAR = 0 SET @DT_LANCE = '20261119 16:00'   -- AGO futura: lances ja registrados ate a data de referencia
SET @DT_APUR = DATEADD(HOUR, 10, @DT)

-- lances: ~14% das cotas ativas ofertam (inclusive inadimplentes, que serao desclassificadas)
DECLARE C CURSOR LOCAL FAST_FORWARD FOR
    SELECT C.CD_COTA, Z.H
      FROM TB_COTA C
     CROSS APPLY (SELECT ABS(CAST(HASHBYTES('MD5', 'L' + CAST(C.CD_COTA AS VARCHAR) + '-' + CAST(@NR AS VARCHAR)) AS INT)) AS H) Z
     WHERE C.CD_GRUPO = @CD_GRUPO AND C.ID_SITUACAO = 1 AND C.DT_ADESAO < @DT_LANCE
       AND Z.H % 100 < 14
OPEN C
FETCH NEXT FROM C INTO @CD_COTA, @H
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @PC = 10 + (@H / 100 % 400) / 10.0
    SET @EMB = CASE WHEN @H / 40000 % 4 = 0 THEN CASE WHEN @PC / 2 > 25 THEN 25 ELSE ROUND(@PC / 2, 1) END
                    WHEN @H / 40000 % 23 = 7 THEN 30     -- acima do maximo: desclassificado
                    ELSE 0 END
    EXEC SP_REGISTRA_LANCE @CD_AGO, @CD_COTA, 1, @PC, @EMB, 2, @DT_LANCE
    FETCH NEXT FROM C INTO @CD_COTA, @H
END
CLOSE C
DEALLOCATE C

IF @APURAR = 1
BEGIN
    UPDATE TB_ASSEMBLEIA
       SET NR_EXTRACAO = 5850 + @NR * 8,
           NR_PREMIO_1 = RIGHT('00000' + CAST(ABS(CAST(HASHBYTES('MD5', 'P1-' + CAST(@CD_AGO AS VARCHAR)) AS INT)) % 100000 AS VARCHAR), 5),
           NR_PREMIO_2 = RIGHT('00000' + CAST(ABS(CAST(HASHBYTES('MD5', 'P2-' + CAST(@CD_AGO AS VARCHAR)) AS INT)) % 100000 AS VARCHAR), 5),
           NR_PREMIO_3 = RIGHT('00000' + CAST(ABS(CAST(HASHBYTES('MD5', 'P3-' + CAST(@CD_AGO AS VARCHAR)) AS INT)) % 100000 AS VARCHAR), 5),
           NR_PREMIO_4 = RIGHT('00000' + CAST(ABS(CAST(HASHBYTES('MD5', 'P4-' + CAST(@CD_AGO AS VARCHAR)) AS INT)) % 100000 AS VARCHAR), 5),
           NR_PREMIO_5 = RIGHT('00000' + CAST(ABS(CAST(HASHBYTES('MD5', 'P5-' + CAST(@CD_AGO AS VARCHAR)) AS INT)) % 100000 AS VARCHAR), 5)
     WHERE CD_ASSEMBLEIA = @CD_AGO
    EXEC SP_APURA_ASSEMBLEIA @CD_AGO, 3, @DT_APUR
END
GO

/* Liberacao dos creditos (15 a 40 dias apos a contemplacao) ---------------- */
CREATE PROCEDURE #LIBERA_CREDITOS
    @DT_ATE DATETIME
AS
SET NOCOUNT ON
DECLARE @CD INT, @DT DATETIME, @FAV VARCHAR(150)
DECLARE C CURSOR LOCAL FAST_FORWARD FOR
    SELECT T.CD_CONTEMPLACAO,
           DATEADD(HOUR, 15, DATEADD(DAY, 15 + T.CD_CONTEMPLACAO * 7 % 26, T.DT_CONTEMPLACAO)),
           CASE T.CD_CONTEMPLACAO % 6 WHEN 0 THEN 'AUTOPAMPA VEICULOS LTDA' WHEN 1 THEN 'SERRA MOTORS COMERCIO DE VEICULOS LTDA'
                WHEN 2 THEN 'GUAIBA AUTOMOVEIS LTDA' WHEN 3 THEN 'SUL CARROS SEMINOVOS LTDA'
                WHEN 4 THEN 'PARTICULAR - VENDA DE VEICULO USADO' ELSE 'CAMPANHA VEICULOS LTDA' END
      FROM TB_CONTEMPLACAO T INNER JOIN TB_COTA C ON C.CD_COTA = T.CD_COTA
     WHERE C.CD_GRUPO = 4 AND T.ID_SITUACAO = 1
       AND DATEADD(HOUR, 15, DATEADD(DAY, 15 + T.CD_CONTEMPLACAO * 7 % 26, T.DT_CONTEMPLACAO)) <= @DT_ATE
     ORDER BY 2
OPEN C
FETCH NEXT FROM C INTO @CD, @DT, @FAV
WHILE @@FETCH_STATUS = 0
BEGIN
    EXEC SP_LIBERA_CREDITO @CD, @DT, @FAV, 3
    FETCH NEXT FROM C INTO @CD, @DT, @FAV
END
CLOSE C
DEALLOCATE C
GO

/* Vendas do 002071 e constituicao ------------------------------------------ */
DECLARE @K INT, @R BIGINT, @DT DATETIME, @BEM INT, @VEND INT, @CONS INT
SET @R = 2071
SET @K = 1
WHILE @K <= 80
BEGIN
    SET @R = (@R * 1103515245 + 12345) % 2147483648
    SET @DT = DATEADD(MINUTE, CAST(540 + @R % 540 AS INT), DATEADD(DAY, (@K - 1) * 98 / 80, '20240304'))
    SET @BEM = CASE WHEN @R % 10 < 3 THEN 6 WHEN @R % 10 < 6 THEN 7 WHEN @R % 10 < 9 THEN 8 ELSE 9 END
    SET @VEND = (@R / 65536) % 11 + 1
    SET @CONS = 160 + @K
    EXEC #VENDE 4, @CONS, @BEM, @VEND, @DT
    SET @K = @K + 1
END

EXEC SP_CONSTITUI_GRUPO 4, '20240625', 3

-- 1a AGO (constituicao)
EXEC #REALIZA_AGO 4, 1
GO

/* Historico mensal ---------------------------------------------------------- */
DECLARE @DT_MES DATETIME, @AM INT, @DT_EMISSAO DATETIME, @DT_FIM_MES DATETIME, @DT_AGO DATETIME, @APURAR BIT,
        @CD_COTA_DES INT, @DT_DES DATETIME
CREATE TABLE #RESUMO (NR_GRUPO CHAR(6), QT INT, VL MONEY)

SET @DT_MES = '20240701'
WHILE @DT_MES <= '20261101'
BEGIN
    SET @AM = YEAR(@DT_MES) * 100 + MONTH(@DT_MES)
    SET @DT_EMISSAO = DATEADD(HOUR, 6, DATEADD(DAY, 4, @DT_MES))
    SET @DT_FIM_MES = DATEADD(MINUTE, -1, DATEADD(MONTH, 1, @DT_MES))

    -- pagamentos ate a vespera da emissao (atrasados de meses anteriores)
    EXEC #EXECUTA_PAGAMENTOS @DT_EMISSAO

    INSERT INTO #RESUMO EXEC SP_EMITE_COBRANCA @AM, @DT_EMISSAO, 1
    EXEC #PLANEJA_PAGAMENTOS @AM

    -- desistencias (pedido do consorciado no dia 10)
    IF @AM IN (202504, 202509)
    BEGIN
        SELECT TOP 1 @CD_COTA_DES = CD_COTA FROM TB_COTA
         WHERE CD_GRUPO = 4 AND ID_SITUACAO = 1 AND NR_COTA >= CASE @AM WHEN 202504 THEN 15 ELSE 44 END
         ORDER BY NR_COTA
        SET @DT_DES = DATEADD(HOUR, 11, DATEADD(DAY, 9, @DT_MES))
        EXEC #EXECUTA_PAGAMENTOS @DT_DES
        DELETE FROM #PAGTO_PLANEJADO WHERE FL_BAIXADO = 'N' AND CD_PARCELA IN (SELECT CD_PARCELA FROM TB_PARCELA WHERE CD_COTA = @CD_COTA_DES)
        EXEC SP_DESISTE_COTA @CD_COTA_DES, 2, @DT_DES, 'Pedido do consorciado (mudanca de cidade)'
    END

    -- assembleia do dia 25: pagamentos ate a vespera, depois a AGO
    -- (novembro/2026 fica agendada, com lances, para apurar na tela)
    SET @DT_AGO = DATEADD(DAY, 24, @DT_MES)
    EXEC #EXECUTA_PAGAMENTOS @DT_AGO
    EXEC #LIBERA_CREDITOS @DT_AGO
    SET @APURAR = CASE WHEN @AM < 202611 THEN 1 ELSE 0 END
    EXEC #REALIZA_AGO 4, @APURAR

    EXEC #EXECUTA_PAGAMENTOS @DT_FIM_MES
    IF @AM < 202611 EXEC #LIBERA_CREDITOS @DT_FIM_MES

    SET @DT_MES = DATEADD(MONTH, 1, @DT_MES)
END

-- atrasados e liberacoes ate a data de referencia
EXEC #EXECUTA_PAGAMENTOS '20261120 23:59'
EXEC #LIBERA_CREDITOS '20261120 23:59'

-- batch noturno de 20/11/2026: exclusao por inadimplencia
EXEC SP_EXCLUI_INADIMPLENTES '20261120 23:00', 1

SELECT NR_GRUPO, SUM(QT) AS PARCELAS_EMITIDAS, SUM(VL) AS VALOR_EMITIDO FROM #RESUMO GROUP BY NR_GRUPO
GO

DROP PROCEDURE #VENDE
